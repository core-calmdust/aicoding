// The board's geometry, the hash keys, the start positions and the board's 12 symmetries for the native tools (nn.c):
//   node agon/tools/nnue/gen_geo.js   → agon/tools/nnue/geo.h (checked in: run.sh needs no Node)
const path = require('path'), fs = require('fs');
const E = require(path.join(__dirname, '..', '..', 'engine.js'));
const C = E.coreArrays; if (!C) throw new Error('core-wasm.js did not load');
const N = 91;
E.setRule('std'); const s = new E.Pos(); E.setRule('place'); const p = new E.Pos(); E.setRule('std');
// cells row by row from the top, axial (q, r): the same walk as engine.js
const Q = [], R = [], IDX = new Map();
for (let r = -5; r <= 5; r++) for (let q = Math.max(-5, -5 - r); q <= Math.min(5, 5 - r); q++) { IDX.set(q + ',' + r, Q.length); Q.push(q); R.push(r); }
const SYM = [];
for (const refl of [0, 1]) for (let k = 0; k < 6; k++) {
  SYM.push(Array.from({ length: N }, (_, i) => {
    let q = Q[i], r = R[i]; if (refl) [q, r] = [r, q];
    for (let j = 0; j < k; j++) [q, r] = [-r, q + r];   // 60° about the throne
    return IDX.get(q + ',' + r);
  }));
}
for (const m of SYM) if (new Set(m).size !== N || m.some(x => x === undefined)) throw new Error('bad symmetry');
if (SYM[3].some((x, i) => x !== N - 1 - i)) throw new Error('rotation by 180° is not N - 1 - i');
const arr = a => Array.from(a).join(',');
fs.writeFileSync(path.join(__dirname, 'geo.h'), `// generated by agon/tools/nnue/gen_geo.js from agon/engine.js — do not edit
static const int GEO_INIT[${C.geo.length}] = { ${arr(C.geo)} };
static const unsigned ZT_INIT[${C.zt.length}] = { ${C.zt.map(x => (x >>> 0) + 'u').join(',')} };
static const signed char START_STD[${N}] = { ${arr(s.sq)} };
static const signed char START_PLACE[${N}] = { ${arr(p.sq)} };
static const unsigned char SYM[12][${N}] = { ${SYM.map(m => '{ ' + m.join(',') + ' }').join(',\n  ')} };
`);
console.log('geo.h written');

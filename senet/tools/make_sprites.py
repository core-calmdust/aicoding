# Renders senet/tools/sprites.html in headless Chrome and writes senet/sprites.js (webp data URLs of the 3D pieces and sticks,
# used by senet/board2d.js). Needs a local server on :8765 at the repository root (python3 -m http.server 8765).
import asyncio, base64, io, sys, os
from playwright.async_api import async_playwright
from PIL import Image
THREE = os.environ.get('THREE_JS')   # (offline: a local copy of three.min.js r128)
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
async def main():
  async with async_playwright() as p:
    b = await p.chromium.launch(executable_path=os.environ.get('CHROME', '/usr/bin/google-chrome'), args=['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'])
    ctx = await b.new_context()
    if THREE:
      src = open(THREE).read()
      await ctx.route('**/three.min.js', lambda r: r.fulfill(status=200, content_type='application/javascript', body=src))
    pg = await ctx.new_page(); await pg.goto('http://localhost:8765/senet/tools/sprites.html'); await pg.wait_for_function('window.ready', timeout=30000)
    await pg.wait_for_timeout(800)
    out = {}
    def webp(du, q=88):
      im = Image.open(io.BytesIO(base64.b64decode(du.split(',')[1]))).convert('RGBA'); bb = io.BytesIO(); im.save(bb, 'WEBP', quality=q, method=6)
      if '--png' in sys.argv: im.save(f'/tmp/sn_{len(out)}.png')
      return 'data:image/webp;base64,' + base64.b64encode(bb.getvalue()).decode()
    for look in ['tut', 'faience', 'gold', 'modern']:
      for side in [0, 1]:
        await pg.evaluate(f"renderPiece({side}, '{look}', 200, 24)")   # (first render compiles: draw twice so the textures are up)
        await pg.wait_for_timeout(300)
        out[f'{look}{side}'] = webp(await pg.evaluate(f"renderPiece({side}, '{look}', 200, 24)"))
    for white in [1, 0]:
      await pg.evaluate(f"renderStick({white}, 56, 300)"); await pg.wait_for_timeout(200)
      out[f'stick{white}'] = webp(await pg.evaluate(f"renderStick({white}, 56, 300)"))
    await b.close()
  js = '// generated by senet/tools/make_sprites.py from the 3D models (atlas/models/senet.js) — do not edit\nwindow.SENET_SPRITES = {\n' + ',\n'.join(f'  {k}: "{v}"' for k, v in out.items()) + '\n};\n'
  open(os.path.join(ROOT, 'senet', 'sprites.js'), 'w').write(js)
  print('wrote senet/sprites.js', len(js), 'bytes')
asyncio.run(main())

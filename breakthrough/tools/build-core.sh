#!/bin/sh
# Build the WebAssembly search (core.c) into core-wasm.js (base64: engine.js loads it synchronously in a worker and in Node).
cd "$(dirname "$0")/.."
W="clang --target=wasm32 -nostdlib -fno-builtin -O3 -w -Wl,--no-entry -Wl,--export-dynamic -Wl,--allow-undefined -Wl,-z,stack-size=4194304 -Wl,--initial-memory=33554432"
$W -msimd128 -o /tmp/bt-core-simd.wasm core.c || exit 1
$W -o /tmp/bt-core.wasm core.c || exit 1
node -e "const f=require('fs'),a=f.readFileSync('/tmp/bt-core-simd.wasm'),b=f.readFileSync('/tmp/bt-core.wasm');f.writeFileSync('core-wasm.js','// generated by tools/build-core.sh from core.c — do not edit\nself.BT_WASM=\''+a.toString('base64')+'\';\nself.BT_WASM0=\''+b.toString('base64')+'\';\n');console.log('core-wasm.js', a.length, '+', b.length, 'bytes of wasm')"

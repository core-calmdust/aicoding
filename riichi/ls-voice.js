// ---------------------------------------------------------------- 丁寧語 → クジャクパイの話し言葉
// verbs: the stem before ます, to the plain form (godan i-row → u-row; ichidan e-row / できる・見る … + る)
const U = { い: 'う', き: 'く', ぎ: 'ぐ', し: 'す', ち: 'つ', に: 'ぬ', び: 'ぶ', み: 'む', り: 'る' };
const A = { い: 'わ', き: 'か', ぎ: 'が', し: 'さ', ち: 'た', に: 'な', び: 'ば', み: 'ま', り: 'ら' };
const O = { い: 'お', き: 'こ', ぎ: 'ご', し: 'そ', ち: 'と', に: 'の', び: 'ぼ', み: 'も', り: 'ろ' };
const TA = { い: 'った', ち: 'った', り: 'った', き: 'いた', ぎ: 'いだ', し: 'した', に: 'んだ', び: 'んだ', み: 'んだ' };
const ICHI_I = /(でき|出来|見|[てで]み|起き|生き|着|似|浴び|信じ|感じ|閉じ|落ち|借り|足り|降り|下り|飽き|延び|伸び)$/;
const GODAN_SU = /(^|[^一-龠])[一-龠]し$|(かえ|ため|なく|さが|はな|もど|ずら|へら|ふや|のこ|だ|お|とお|はず|くず|なお|かく|ころ|ゆる|まわ|うつ)し$/;   // (残します・探します・外します …: godan)   // i-row stems that are ichidan
function kind(stem) {
  if (stem === 'し' || /し$/.test(stem) && !GODAN_SU.test(stem)) return 'suru';   // (説明します・リーチします・どきどきします; 1 kanji + し is godan: 残します)
  if (/来$/.test(stem)) return 'kuru';
  if (stem === 'い' || /(^|[てでがはもをにと])い$/.test(stem)) return 'ichi';       // (います・ています・牌がいます)
  const last = stem.slice(-1);
  if (/[えけげせぜてでねへべめれ]/.test(last) || ICHI_I.test(stem)) return 'ichi';
  if (U[last]) return 'go';
  return 'ichi';
}
function plain(stem, form) {   // form: 'u' (する) · 'nai' (しない) · 'ta' (した) · 'you' (しよう) · 'te' (している → してる)
  const k = kind(stem), last = stem.slice(-1), body = stem.slice(0, -1);
  if (k === 'suru') { const b = stem.slice(0, -1); return b + { u: 'する', nai: 'しない', ta: 'した', you: 'しよう' }[form]; }
  if (k === 'kuru') { const b = stem.slice(0, -1); return b + { u: '来る', nai: '来ない', ta: '来た', you: '来よう' }[form]; }
  if (stem.endsWith('あり') && form === 'nai') return stem.slice(0, -2) + 'ない';
  if (k === 'ichi') return stem + { u: 'る', nai: 'ない', ta: 'た', you: 'よう' }[form];
  if (/行き$|いき$/.test(stem) && form === 'ta') return body + 'った';
  return body + { u: U[last], nai: A[last] + 'ない', ta: TA[last], you: O[last] + 'う' }[form];
}
// a stable pick from the sentence itself (the same text always reads the same)
const hash = s => { let h = 7; for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) % 100003; return h; };
function voice(s) {
  if (!s || typeof s !== 'string') return s;
  if (s.startsWith(MARK)) return s.slice(1);
  let t = s;
  t = t.replace(/小町/g, 'ぼく').replace(/わたし/g, 'ぼく');
  t = t.replace(/([ぁ-ん一-龠ァ-ヶー]+?)ますか[？?]/g, (m, st) => plain(st, 'u') + 'かな？');
  // set phrases first
  const P = [
    [/ていませんか[？?]/g, 'てない？'], [/ていません/g, 'てない'], [/ていました/g, 'てた'], [/ています/g, 'てる'], [/ていきましょっ/g, 'ていこう'],
    [/でいます/g, 'でる'], [/ちゃいました/g, 'ちゃった'], [/ちゃいます/g, 'ちゃう'], [/じゃいます/g, 'じゃう'],
    [/てください/g, 'てね'], [/でください/g, 'でね'], [/ください/g, 'ちょうだい'],
    [/でしょう[？?]/g, 'でしょ？'], [/でしょうか[？?]/g, 'かな？'], [/でしょう/g, 'だろうね'],
    [/ですよね[？?]/g, 'だよね？'], [/ですか[？?]/g, 'かな？'], [/でした/g, 'だった'],
    [/ありません/g, 'ない'], [/ありました/g, 'あった'], [/あります/g, 'ある'],
    [/いけません/g, 'いけない'], [/なりません/g, 'ならない'], [/できません/g, 'できない'], [/しません/g, 'しない'],
    [/大丈夫です/g, '大丈夫'], [/どうぞ/g, 'どうぞ'],
  ];
  for (const [a, b] of P) t = t.replace(a, b);
  // 〜ましょう / ましょっ / ましょ → volitional
  t = t.replace(/([ぁ-ん一-龠ァ-ヶー]+?)ましょ[うっ]?/g, (m, st) => plain(st, 'you'));
  t = t.replace(/([ぁ-ん一-龠ァ-ヶー]+?)ません/g, (m, st) => plain(st, 'nai'));
  t = t.replace(/([ぁ-ん一-龠ァ-ヶー]+?)ました/g, (m, st) => plain(st, 'ta'));
  t = t.replace(/([ぁ-ん一-龠ァ-ヶー]+?)ます/g, (m, st) => plain(st, 'u'));
  // です
  t = t.replace(/んですよ/g, 'んだ').replace(/んです/g, 'んだ');
  t = t.replace(/いですよ/g, 'いよ').replace(/いです/g, 'い');   // (adjectives: 安いです → 安い)
  t = t.replace(/ですよ/g, 'だよ').replace(/ですね/g, 'だね').replace(/です/g, 'だ');
  t = t.replace(/だ([♪！!。…〜])/g, (m, p) => p === '。' ? 'だよ。' : 'だ' + p);
  t = t.replace(/だよ〜/g, 'だよ〜');
  // short praise at the head of a line: 「正解だ！」「さすがだ！」 → 「正解！」「さすが！」
  t = t.replace(/(^|[。！!♪？?…]\s*)([^\s。！!♪？?…、]{1,5})だ！/g, '$1$2！');
  t = t.replace(/(どれ|どっち|どの[^\s。？?]{0,6}|何|どこ|どう)でしょ？/g, '$1かな？');
  // no two sentences in a row ending 〜よ (the common rule): the first one loses its よ
  { const ss = t.split(/(?<=[。！!♪])/), yo = x => /よ[。！!♪]\s*$/.test(x);
    for (let i = 1; i < ss.length; i++) if (yo(ss[i]) && yo(ss[i - 1])) ss[i - 1] = ss[i - 1].replace(/だよ([。！!♪]\s*)$/, 'だ$1').replace(/よ([。！!♪]\s*)$/, '$1');
    t = ss.join(''); }
  // the verbal tic: about one bubble in three ends one sentence with クジャ (not after ん・の, not on a question)
  const sents = t.split(/(?<=[。！!♪])/);
  const N_END = /んだ[よね]?([。！!♪])$/, END = /([^んの…だ])(だよ|だね|だ|よ|ね)([。！!♪])$/;   // (〜しないんだよ。 → 〜しないクジャ！ · 〜形だよ♪ → 〜形クジャ♪)
  const can = sents.map(x => !/[？?]/.test(x) && (N_END.test(x) || END.test(x)) && !/クジャ/.test(x) && x.trim().length > 6);
  if (can.some(Boolean) && hash(s) % 10 < 6) {
    let k = -1; for (let i = sents.length - 1; i >= 0; i--) if (can[i]) { k = i; break; }
    const q = p => (p === '。' ? '！' : p);
    sents[k] = N_END.test(sents[k]) ? sents[k].replace(N_END, (m, p) => 'クジャ' + q(p)) : sents[k].replace(END, (m, c, a, p) => c + 'クジャ' + q(p));
  }
  t = sents.join('');
  return t;
}


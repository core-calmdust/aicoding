// Writes patterns.h (the pattern sets of engine.js for rvtrain.c / rvlabel.c): for each set, the instances' squares
// (a1 = 0, row-major) and table offsets, in engine.js's order, so the C tools compute the same features as the engine.
//   node tools/train/gen-patterns.js            (run after changing PATTERN_DEFS* in engine.js)
'use strict';
const fs = require('fs'), path = require('path');
const E = require(path.join(__dirname, '../../engine.js'));
const SETS = ['B', 'C'];
const L = ['// generated by tools/train/gen-patterns.js from engine.js: per pattern set, instance squares (a1 = 0, row-major,',
  '// -1 = unused), table offsets and lengths; PT_TOTAL = the size of the pattern tables of one phase', ''];
L.push(`#define PT_NSETS ${SETS.length}`);
L.push(`static const char PT_NAME[PT_NSETS] = { ${SETS.map(s => `'${s}'`).join(', ')} };`);
const ninst = [], total = [], defs = [];
for (const k of SETS) {
  E.useSet(k);
  const pats = E.PATTERNS; const inst = [];
  for (const p of pats) for (const m of p.inst) inst.push({ off: p.offset, len: p.len, sq: m, name: p.name });
  const tot = pats.reduce((a, p) => a + p.size, 0);
  ninst.push(inst.length); total.push(tot); defs.push({ k, inst, pats });
}
L.push(`static const int PT_NINST[PT_NSETS] = { ${ninst.join(', ')} };`);
L.push(`static const int PT_TOTAL[PT_NSETS] = { ${total.join(', ')} };`);
L.push(`#define PT_MAXI ${Math.max(...ninst)}`);
L.push(`static const int PT_OFF[PT_NSETS][PT_MAXI] = {`);
for (const d of defs) L.push(`  { ${d.inst.map(i => i.off).join(',')} },`);
L.push('};');
L.push(`static const int PT_LEN[PT_NSETS][PT_MAXI] = {`);
for (const d of defs) L.push(`  { ${d.inst.map(i => i.len).join(',')} },`);
L.push('};');
L.push(`static const signed char PT_SQ[PT_NSETS][PT_MAXI][10] = {`);
for (const d of defs) L.push(`  { ${d.inst.map(i => '{' + i.sq.concat(Array(10 - i.sq.length).fill(-1)).join(',') + '}').join(',')} },`);
L.push('};');
L.push(`// pattern names, one per table (for the logs): ${defs.map(d => d.k + ': ' + d.pats.map(p => p.name).join(' ')).join(' | ')}`);
fs.writeFileSync(path.join(__dirname, 'patterns.h'), L.join('\n') + '\n');
console.log('patterns.h:', defs.map(d => `${d.k} ${d.inst.length} instances, ${d.pats.length} patterns, ${total[defs.indexOf(d)]} weights/phase`).join('; '));

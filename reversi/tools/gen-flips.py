# Generates the flips() of engine.c (the block between "BEGIN gen-flips" and "END gen-flips"):
# one switch case per square with the ray masks as constants, only the rays of two or more squares.
# usage: python3 tools/gen-flips.py > /tmp/flips.h   (then paste it over the block)
D_UP = [(0, 1), (1, -1), (1, 0), (1, 1)]      # +1 +7 +8 +9 (towards higher squares)
D_DN = [(0, -1), (-1, 1), (-1, 0), (-1, -1)]  # -1 -7 -8 -9
out = []
out.append('/* generated by tools/gen-flips.py: one case per square, only the rays with two or more squares (a flip needs an\n   opponent disc and then an own disc), the masks as constants */')
out.append('#define FU(M, LO) { const u64 o_ = ((O | ~(M)) + (LO)) & (M) & ~O; if (o_ & P) f |= (o_ - (LO)) & (M); }')
out.append('#define FD(M) { const u64 h_ = (M) & ~O; if (h_) { const u64 o_ = 1ULL << (63 - __builtin_clzll(h_)); if (o_ & P) f |= (M) & ~((o_ << 1) - 1); } }')
out.append('static inline u64 flips(int sq, u64 P, u64 O) {')
out.append('  u64 f = 0;')
out.append('  switch (sq) {')
for sq in range(64):
    r0, c0 = sq >> 3, sq & 7
    parts = []
    for dr, dc in D_UP + D_DN:
        r, c, sqs = r0 + dr, c0 + dc, []
        while 0 <= r < 8 and 0 <= c < 8:
            sqs.append(r * 8 + c); r += dr; c += dc
        if len(sqs) < 2: continue
        m = 0
        for q in sqs: m |= 1 << q
        if (dr, dc) in D_UP: parts.append('FU(0x%XULL, 0x%XULL)' % (m, 1 << sqs[0]))
        else: parts.append('FD(0x%XULL)' % m)
    out.append('  case %d: %s break;' % (sq, ' '.join(parts)))
out.append('  }')
out.append('  return f;')
out.append('}')
out.append('#undef FU')
out.append('#undef FD')
print('\n'.join(out))

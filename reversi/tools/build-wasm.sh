#!/bin/sh
# Build the C search core (engine.c) → engine-wasm.js (the WebAssembly module as base64, for importScripts in the worker)
# and engine.wasm (for Node tools). engine.js falls back to its own JS search when neither is available.
set -e
cd "$(dirname "$0")/.."
clang --target=wasm32 -O3 -msimd128 -nostdlib -fno-builtin -w -Wl,--no-entry -Wl,--export-dynamic -Wl,--allow-undefined -o engine.wasm engine.c
node -e "const b=require('fs').readFileSync('engine.wasm').toString('base64');require('fs').writeFileSync('engine-wasm.js','// generated by tools/build-wasm.sh from engine.c\nself.REVERSI_WASM = \"'+b+'\";\n')"
ls -l engine.wasm engine-wasm.js
# engine_mt.wasm: several threads on one shared memory (Lazy SMP, engine.c with -DMT) for pro/ (cross-origin isolated)
clang --target=wasm32 -O3 -msimd128 -matomics -mbulk-memory -DMT -nostdlib -fno-builtin -w -Wl,--no-entry -Wl,--export-dynamic \
  -Wl,--shared-memory -Wl,--import-memory -Wl,--max-memory=1073741824 -Wl,--allow-undefined -o engine_mt.wasm engine.c

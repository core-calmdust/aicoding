#!/bin/sh
# Build the C search core (engine.c) → engine-wasm.js (the WebAssembly module as base64, for importScripts in the worker)
# and engine.wasm (for Node tools). engine.js falls back to its own JS search when neither is available.
set -e
cd "$(dirname "$0")/.."
clang --target=wasm32 -O3 -nostdlib -fno-builtin -w -Wl,--no-entry -Wl,--export-dynamic -Wl,--allow-undefined -o engine.wasm engine.c
node -e "const b=require('fs').readFileSync('engine.wasm').toString('base64');require('fs').writeFileSync('engine-wasm.js','// generated by tools/build-wasm.sh from engine.c\nself.REVERSI_WASM = \"'+b+'\";\n')"
ls -l engine.wasm engine-wasm.js

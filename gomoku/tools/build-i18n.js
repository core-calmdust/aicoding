// Build gomoku/i18n.js: the site-wide UI strings shared with chess (online play, rated games, review, ...) +
// the gomoku-specific strings in tools/i18n/<lang>.json (which override the shared ones).
// node tools/build-i18n.js
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..'), CHESS = path.join(ROOT, '..', 'chess');
global.window = {};
require(path.join(CHESS, 'i18n.js'));
for (const f of ['i18n_basics.js', 'i18n_coach.js']) { try { require(path.join(CHESS, f)); } catch (e) {} }
const C = window.I18N;
const LANGS = ['ja', 'en', 'zh', 'ko', 'es', 'fr', 'pt', 'de', 'hi', 'ar'];
const SHARED = JSON.parse(fs.readFileSync(path.join(__dirname, 'i18n', 'shared-keys.json'), 'utf8'));
const out = {};
for (const L of LANGS) {
  const o = {};
  for (const k of SHARED) { const v = (C[L] || {})[k]; if (v !== undefined) o[k] = v; }
  let g = {}; try { g = JSON.parse(fs.readFileSync(path.join(__dirname, 'i18n', L + '.json'), 'utf8')); } catch (e) {}
  Object.assign(o, g);
  out[L] = o;
}
let s = '// UI strings for Gomoku & Renju — ja / en / zh (Simplified) / ko / es / fr / pt / de / hi / ar\n// generated by tools/build-i18n.js — edit tools/i18n/*.json\nwindow.I18N = {\n';
s += LANGS.map(L => L + ': ' + JSON.stringify(out[L], null, 0).replace(/","/g, '",\n  "')).join(',\n') + '\n};\n';
fs.writeFileSync(path.join(ROOT, 'i18n.js'), s);
console.log(LANGS.map(L => L + ':' + Object.keys(out[L]).length).join(' '));

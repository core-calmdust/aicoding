// Splits atlas/updnews.js (the 「この日は？」 lines, all 14 languages, ~0.9 MB — the source to edit) into one small file per
// language, atlas/updnews/<lang>.js (~70 KB), so 「すべての更新」 loads only the reader's language (2026-11-17).
// Run after editing atlas/updnews.js: node tools/updnews-split.js — then bump UPDNEWS_V in atlas/app.js.
const fs = require('fs'), path = require('path');
global.window = {}; require('../atlas/updnews.js');
const N = window.AtlasNews, OUT = path.join(__dirname, '../atlas/updnews');
const LANGS = Object.keys(N.LABEL);
fs.mkdirSync(OUT, { recursive: true });
LANGS.forEach(l => {
  const pick = m => (m && (m[l] != null ? m[l] : m.en)) || '';
  const F = {}; Object.keys(N.FACTS).forEach(k => { const v = pick(N.FACTS[k]); if (v) F[k] = v; });
  const T = {}; Object.keys(N.TAGS).forEach(k => { T[k] = pick(N.TAGS[k]); });
  const body = `/* generated by tools/updnews-split.js from atlas/updnews.js — do not edit (language: ${l}) */\n`
    + `(function (l, F, LB, T) { const N = window.AtlasNews = window.AtlasNews || { FACTS: {}, LABEL: {}, TAGS: {}, has: {} }; N.has = N.has || {};\n`
    + `  Object.keys(F).forEach(k => { (N.FACTS[k] = N.FACTS[k] || {})[l] = F[k]; }); N.LABEL[l] = LB; Object.keys(T).forEach(k => { (N.TAGS[k] = N.TAGS[k] || {})[l] = T[k]; }); N.has[l] = 1;\n`
    + `})(${JSON.stringify(l)}, ${JSON.stringify(F)}, ${JSON.stringify(pick(N.LABEL))}, ${JSON.stringify(T)});\n`;
  fs.writeFileSync(path.join(OUT, l + '.js'), body);
});
console.log('wrote', LANGS.length, 'files to atlas/updnews/');

#!/usr/bin/env python3
"""Build go/i18n.js from tools/i18n/<lang>.json (UI strings). Missing keys fall back to en → ja in the page."""
import json, os
D = os.path.dirname(os.path.abspath(__file__))
LANGS = ['ja', 'en', 'zh', 'ko', 'es', 'fr', 'pt', 'de', 'hi', 'ar', 'ru', 'zh-TW', 'id', 'tr']
out = {}
for l in LANGS:
    p = os.path.join(D, 'i18n', l + '.json')
    if os.path.exists(p):
        out[l] = json.load(open(p, encoding='utf-8'))
        po = os.path.join(D, 'i18n', 'online_' + l + '.json')
        if os.path.exists(po): out[l].update(json.load(open(po, encoding='utf-8')))
    else:
        out[l] = {}
js = '// Generated by tools/build_i18n.py from tools/i18n/*.json — do not edit by hand.\nwindow.I18N = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n'
# hand-written additions after the generated line 2 (e.g. the ls.toList / ls.toOpen fallback block) are kept as they are
OUT = os.path.join(D, '..', 'i18n.js')
if os.path.exists(OUT):
    old = open(OUT, encoding='utf-8').read().split('\n', 2)
    if len(old) == 3 and old[1].startswith('window.I18N = '): js += old[2]
open(OUT, 'w', encoding='utf-8').write(js)
print('i18n.js', len(js), 'bytes', {l: len(v) for l, v in out.items()})
